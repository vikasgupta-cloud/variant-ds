/**
 * Style Dictionary v4 pipeline (spec §1, §6, §8).
 *
 * Reads tokens/*.json → src/styles/tokens/*.css (+ tokens.json).
 * outputReferences: true is mandatory — aliases emit var(--name), not flattened hex.
 * Fails the build on missing $description, broken references, or duplicate CSS paths across layers.
 */
import { mkdirSync, writeFileSync, rmSync, readFileSync } from "node:fs";
import { basename, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";
import { formats, transforms } from "style-dictionary/enums";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokensDir = join(root, "tokens");
const outDir = join(root, "src/styles/tokens");

const FILES = {
  primitive: "primitive.json",
  roleLight: "role.light.json",
  roleDark: "role.dark.json",
  surface: "surface.json",
  structure: "structure.json",
  overlay: "overlay.json",
  component: "component.json",
};

const nameTransform = {
  type: "name",
  transform(token) {
    return token.path.join("-");
  },
};

const cssTransforms = [
  transforms.attributeCti,
  "name/variant-path",
  transforms.colorCss,
  transforms.cubicBezierCss,
];

function header(layer) {
  return `/**\n * DO NOT EDIT — generated by Style Dictionary from tokens/*.json\n * Layer: ${layer}\n * outputReferences: true\n */\n\n`;
}

async function loadJson(name) {
  return (await import(new URL(`../tokens/${name}`, import.meta.url), { with: { type: "json" } }))
    .default;
}

/** Walk a DTCG token tree and collect leaf tokens. */
function collectLeaves(node, file, prefix = [], out = []) {
  if (node === null || typeof node !== "object" || Array.isArray(node)) return out;
  if ("$value" in node || "value" in node) {
    out.push({
      path: prefix.join("."),
      file,
      description: node.$description ?? node.description ?? node.comment,
      value: node.$value ?? node.value,
      type: node.$type ?? node.type,
    });
    return out;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    collectLeaves(child, file, [...prefix, key], out);
  }
  return out;
}

/** `{neutral.950}` → `neutral-950`; non-refs return null. */
function aliasFromValue(value) {
  if (typeof value !== "string") return null;
  const m = value.match(/^\{([a-z0-9.-]+)\}$/i);
  if (!m) return null;
  return m[1].replace(/\./g, "-");
}

function leafType(value, explicit) {
  if (explicit) return explicit;
  if (
    value &&
    typeof value === "object" &&
    !Array.isArray(value) &&
    ("fontFamily" in value || "fontSize" in value)
  ) {
    return "typography";
  }
  if (typeof value === "string" && (value.startsWith("#") || value.startsWith("{"))) {
    return "color";
  }
  if (typeof value === "number") return "dimension";
  if (typeof value === "string" && /px|rem|em|ms|s|%$/.test(value)) return "dimension";
  return "other";
}

/** Expand typography composites into per-axis CSS custom properties. */
function emitTypographyCss(typography) {
  const lines = [];
  function walk(node, prefix) {
    if (!node || typeof node !== "object") return;
    if ("$value" in node) {
      const v = node.$value;
      const name = prefix.join("-");
      lines.push(`  --${name}-font-family: ${v.fontFamily};`);
      lines.push(`  --${name}-font-size: ${v.fontSize};`);
      lines.push(`  --${name}-font-weight: ${v.fontWeight};`);
      lines.push(`  --${name}-line-height: ${v.lineHeight};`);
      lines.push(`  --${name}-letter-spacing: ${v.letterSpacing};`);
      return;
    }
    for (const [key, child] of Object.entries(node)) {
      if (key.startsWith("$")) continue;
      walk(child, [...prefix, key]);
    }
  }
  walk(typography, ["typography"]);
  if (!lines.length) return "";
  return `:root {\n${lines.join("\n")}\n}\n`;
}

/** Clone primitive without typography — SD cssVariables cannot emit object composites. */
function primitiveWithoutTypography(primitive) {
  const clone = structuredClone(primitive);
  delete clone.typography;
  return clone;
}

/**
 * Flat catalog consumed by TokenBrowser / editor (spec §5, §8).
 * One entry per CSS custom property name. Mode/context variants carry valueByMode / valueByContext.
 */
function buildTokenCatalog({
  primitive,
  roleLight,
  roleDark,
  surface,
  structure,
  overlay,
  component,
}) {
  const catalog = [];

  function push({ name, path, layer, type, description, value, valueByMode, valueByContext }) {
    const alias = aliasFromValue(
      valueByMode?.light ?? valueByMode?.dark ?? valueByContext?.["light/canvas"] ?? value,
    );
    catalog.push({
      name,
      path,
      cssVar: `--${name}`,
      layer,
      type: leafType(value ?? valueByMode?.light ?? Object.values(valueByContext ?? {})[0], type),
      description: description ?? "",
      value: value ?? null,
      valueByMode: valueByMode ?? null,
      valueByContext: valueByContext ?? null,
      alias,
    });
  }

  for (const leaf of collectLeaves(primitive, FILES.primitive)) {
    push({
      name: leaf.path.replace(/\./g, "-"),
      path: leaf.path.split("."),
      layer: "primitive",
      type: leaf.type,
      description: leaf.description,
      value: leaf.value,
    });
  }

  const darkByPath = new Map(
    collectLeaves(roleDark, FILES.roleDark).map((l) => [l.path, l]),
  );
  for (const leaf of collectLeaves(roleLight, FILES.roleLight)) {
    const dark = darkByPath.get(leaf.path);
    push({
      name: leaf.path.replace(/\./g, "-"),
      path: leaf.path.split("."),
      layer: "role",
      type: "color",
      description: leaf.description,
      valueByMode: {
        light: leaf.value,
        dark: dark?.value ?? leaf.value,
      },
    });
  }

  // Surface CSS vars are `--surface-*`; values vary by mode × context.
  const surfaceKeys = Object.keys(surface.light.canvas);
  for (const key of surfaceKeys) {
    const valueByContext = {};
    let description = surface.light.canvas[key].$description;
    for (const mode of ["light", "dark"]) {
      for (const context of ["canvas", "surface", "surface-raised"]) {
        const token = surface[mode][context][key];
        valueByContext[`${mode}/${context}`] = token.$value;
        if (mode === "light" && context === "canvas") description = token.$description;
      }
    }
    push({
      name: `surface-${key}`,
      path: ["surface", key],
      layer: "surface",
      type: "color",
      description,
      valueByContext,
    });
  }

  for (const leaf of collectLeaves(structure, FILES.structure)) {
    push({
      name: leaf.path.replace(/\./g, "-"),
      path: leaf.path.split("."),
      layer: "structure",
      type: leaf.type,
      description: leaf.description,
      value: leaf.value,
    });
  }

  for (const leaf of collectLeaves(overlay, FILES.overlay)) {
    push({
      name: leaf.path.replace(/\./g, "-"),
      path: leaf.path.split("."),
      layer: "overlay",
      type: leaf.type,
      description: leaf.description,
      value: leaf.value,
    });
  }

  // Component: collapse .light/.dark path suffixes into valueByMode on the CSS name.
  const componentByCss = new Map();
  for (const leaf of collectLeaves(component, FILES.component)) {
    const parts = leaf.path.split(".");
    let mode = null;
    if (parts[parts.length - 1] === "light" || parts[parts.length - 1] === "dark") {
      mode = parts.pop();
    }
    const cssPath = parts.join(".");
    const name = cssPath.replace(/\./g, "-");
    if (!componentByCss.has(name)) {
      componentByCss.set(name, {
        name,
        path: parts,
        type: leaf.type,
        description: leaf.description,
        value: null,
        valueByMode: null,
      });
    }
    const entry = componentByCss.get(name);
    if (mode) {
      entry.valueByMode = entry.valueByMode ?? {};
      entry.valueByMode[mode] = leaf.value;
      if (mode === "light") entry.description = leaf.description;
    } else {
      entry.value = leaf.value;
      entry.description = leaf.description;
    }
  }
  for (const entry of componentByCss.values()) {
    push({
      name: entry.name,
      path: entry.path,
      layer: "component",
      type: entry.type,
      description: entry.description,
      value: entry.value,
      valueByMode: entry.valueByMode,
    });
  }

  catalog.sort((a, b) => {
    const layerOrder = {
      primitive: 0,
      role: 1,
      surface: 2,
      structure: 3,
      overlay: 4,
      component: 5,
    };
    const la = layerOrder[a.layer] ?? 9;
    const lb = layerOrder[b.layer] ?? 9;
    if (la !== lb) return la - lb;
    return a.name.localeCompare(b.name);
  });

  return {
    $schema: "variant-ds/token-catalog",
    generated: true,
    tokens: catalog,
  };
}

function validate(layers) {
  const errors = [];
  const seen = new Map();

  for (const { file, leaves } of layers) {
    for (const leaf of leaves) {
      if (!leaf.description || String(leaf.description).trim() === "") {
        errors.push(`Missing description: ${leaf.path} (${file})`);
      }
      const cssPath = leaf.cssPath ?? leaf.path;
      if (seen.has(cssPath)) {
        errors.push(
          `Duplicate token path "${cssPath}" in ${file} and ${seen.get(cssPath)}`,
        );
      } else {
        seen.set(cssPath, file);
      }
    }
  }

  if (errors.length) {
    console.error("\nToken validation failed:\n" + errors.map((e) => `  • ${e}`).join("\n"));
    process.exit(1);
  }
}

/** Resolve `{neutral.500}` → hex using primitive (and nested refs one level). */
function resolveColorRef(value, primitive) {
  if (typeof value !== "string") return value;
  if (value.startsWith("#")) return value;
  const m = value.match(/^\{([a-z0-9-]+)\.([a-z0-9.-]+)\}$/i);
  if (!m) throw new Error(`Cannot resolve color ref: ${value}`);
  const [, family, step] = m;
  const token = primitive[family]?.[step];
  if (!token) throw new Error(`Missing primitive ${family}.${step}`);
  const next = token.$value ?? token.value;
  if (typeof next === "string" && next.startsWith("{")) {
    return resolveColorRef(next, primitive);
  }
  return next;
}

function hexToRgb(hex) {
  const h = hex.replace("#", "");
  const full =
    h.length === 3
      ? h
          .split("")
          .map((c) => c + c)
          .join("")
      : h;
  return {
    r: parseInt(full.slice(0, 2), 16),
    g: parseInt(full.slice(2, 4), 16),
    b: parseInt(full.slice(4, 6), 16),
  };
}

function relativeLuminance({ r, g, b }) {
  const lin = [r, g, b].map((c) => {
    const s = c / 255;
    return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
}

function contrastRatio(hexA, hexB) {
  const l1 = relativeLuminance(hexToRgb(hexA));
  const l2 = relativeLuminance(hexToRgb(hexB));
  const lighter = Math.max(l1, l2);
  const darker = Math.min(l1, l2);
  return (lighter + 0.05) / (darker + 0.05);
}

/**
 * Fail the build if surface/control or surface/border is below 3:1
 * against the role background for that mode × context (6 combinations).
 */
function assertSurfaceLineFillContrast(primitive, roleLight, roleDark, surface) {
  const roleByMode = { light: roleLight, dark: roleDark };
  const contexts = ["canvas", "surface", "surface-raised"];
  const tokens = ["control", "border"];
  const errors = [];
  const rows = [];

  for (const mode of ["light", "dark"]) {
    for (const context of contexts) {
      const bgRef = roleByMode[mode].bg[context].$value;
      const bgHex = resolveColorRef(bgRef, primitive);
      for (const name of tokens) {
        const fgRef = surface[mode][context][name].$value;
        const fgHex = resolveColorRef(fgRef, primitive);
        const ratio = contrastRatio(fgHex, bgHex);
        rows.push({
          mode,
          context,
          name,
          fg: fgRef,
          bg: bgRef,
          ratio: ratio.toFixed(2),
        });
        if (ratio < 3) {
          errors.push(
            `surface/${name} ${mode}/${context}: ${fgRef} on ${bgRef} = ${ratio.toFixed(2)}:1 (need ≥3:1)`,
          );
        }
      }
    }
  }

  console.log("\nSurface control/border contrast (≥3:1 vs context bg):");
  for (const r of rows) {
    const mark = Number(r.ratio) >= 3 ? "✓" : "✗";
    console.log(
      `  ${mark} ${r.mode.padEnd(5)} ${r.context.padEnd(14)} ${r.name.padEnd(7)} ${r.ratio}:1  (${r.fg} on ${r.bg})`,
    );
  }

  if (errors.length) {
    console.error(
      "\nSurface contrast check failed:\n" + errors.map((e) => `  • ${e}`).join("\n"),
    );
    process.exit(1);
  }
}

/**
 * Build one CSS file from source (+ includes for reference resolution).
 * Only tokens from `sourceFile` are emitted; includes resolve aliases.
 */
async function buildCss({
  sourceFile,
  includes = [],
  destination,
  selector,
  tokens,
}) {
  const tmpFile = tokens
    ? join(tokensDir, `_tmp_${destination.replace(/[^\w.-]+/g, "_")}.json`)
    : null;
  if (tmpFile) writeFileSync(tmpFile, JSON.stringify(tokens, null, 2));

  const sourcePath = tmpFile ?? join(tokensDir, sourceFile);
  const sourceBase = basename(sourcePath);

  const sd = new StyleDictionary({
    usesDtcg: true,
    include: includes.map((f) => join(tokensDir, f)),
    source: [sourcePath],
    log: {
      // Referenced primitives are intentionally filtered out of layer files.
      verbosity: "silent",
      errors: { brokenReferences: "throw" },
    },
    hooks: {
      transforms: { "name/variant-path": nameTransform },
    },
    platforms: {
      css: {
        transforms: cssTransforms,
        buildPath: `${outDir}/`,
        files: [
          {
            destination,
            format: formats.cssVariables,
            filter: (token) => basename(token.filePath || "") === sourceBase,
            options: {
              outputReferences: true,
              selector,
              showFileHeader: false,
            },
          },
        ],
      },
    },
  });

  await sd.hasInitialized;
  await sd.buildAllPlatforms();
  const css = readFileSync(join(outDir, destination), "utf8").trim();
  if (tmpFile) {
    rmSync(tmpFile, { force: true });
    rmSync(join(outDir, destination), { force: true });
  }
  return css;
}

/** Pull mode-paired component colors (*.light / *.dark) into separate trees. */
function splitComponentModes(component) {
  const root = structuredClone(component);
  const light = {};
  const dark = {};

  function extract(n, p) {
    if (!n || typeof n !== "object" || Array.isArray(n) || "$value" in n) return;
    for (const k of Object.keys(n)) {
      if (k.startsWith("$")) continue;
      const child = n[k];
      const keys = child && typeof child === "object" ? Object.keys(child) : [];
      const isModePair =
        child &&
        typeof child === "object" &&
        child.light?.$value !== undefined &&
        child.dark?.$value !== undefined &&
        keys.every((x) => x === "light" || x === "dark" || x.startsWith("$"));

      if (isModePair) {
        let lp = light;
        let dp = dark;
        for (const seg of p) {
          lp[seg] ??= {};
          dp[seg] ??= {};
          lp = lp[seg];
          dp = dp[seg];
        }
        lp[k] = child.light;
        dp[k] = child.dark;
        delete n[k];
        continue;
      }
      extract(child, [...p, k]);
    }
  }

  extract(root, []);
  return { root, light, dark };
}

async function main() {
  mkdirSync(outDir, { recursive: true });

  const primitive = await loadJson(FILES.primitive);
  const roleLight = await loadJson(FILES.roleLight);
  const roleDark = await loadJson(FILES.roleDark);
  const surface = await loadJson(FILES.surface);
  const structure = await loadJson(FILES.structure);
  const overlay = await loadJson(FILES.overlay);
  const component = await loadJson(FILES.component);

  // ——— validate descriptions + duplicate CSS paths ———
  const roleLeaves = collectLeaves(roleLight, FILES.roleLight).map((t) => ({
    ...t,
    cssPath: t.path,
  }));
  const componentLeavesRaw = collectLeaves(component, FILES.component).map((t) => ({
    ...t,
    cssPath: t.path.replace(/\.light$/, "").replace(/\.dark$/, ""),
  }));
  const componentCssSeen = new Set();
  const componentLeaves = componentLeavesRaw.filter((t) => {
    if (componentCssSeen.has(t.cssPath)) return false;
    componentCssSeen.add(t.cssPath);
    return true;
  });

  validate([
    {
      file: FILES.primitive,
      leaves: collectLeaves(primitive, FILES.primitive).map((t) => ({
        ...t,
        cssPath: t.path,
      })),
    },
    { file: FILES.roleLight, leaves: roleLeaves },
    {
      file: FILES.structure,
      leaves: collectLeaves(structure, FILES.structure).map((t) => ({
        ...t,
        cssPath: t.path,
      })),
    },
    {
      file: FILES.overlay,
      leaves: collectLeaves(overlay, FILES.overlay).map((t) => ({
        ...t,
        cssPath: t.path,
      })),
    },
    { file: FILES.component, leaves: componentLeaves },
  ]);

  // Descriptions on role.dark + every surface cell (css names intentionally overlap by mode/context)
  for (const leaf of collectLeaves(roleDark, FILES.roleDark)) {
    if (!leaf.description?.trim()) {
      console.error(`\nToken validation failed:\n  • Missing description: ${leaf.path} (${FILES.roleDark})`);
      process.exit(1);
    }
  }
  for (const mode of ["light", "dark"]) {
    for (const context of ["canvas", "surface", "surface-raised"]) {
      for (const [key, token] of Object.entries(surface[mode][context])) {
        if (!token.$description?.trim()) {
          console.error(
            `\nToken validation failed:\n  • Missing description: ${mode}.${context}.${key} (${FILES.surface})`,
          );
          process.exit(1);
        }
      }
    }
  }
  for (const leaf of componentLeavesRaw) {
    if (!leaf.description?.trim()) {
      console.error(`\nToken validation failed:\n  • Missing description: ${leaf.path} (${FILES.component})`);
      process.exit(1);
    }
  }

  assertSurfaceLineFillContrast(primitive, roleLight, roleDark, surface);

  // ——— primitive.css ———
  const primitiveForSd = primitiveWithoutTypography(primitive);
  writeFileSync(
    join(outDir, "primitive.css"),
    header("primitive") +
      (await buildCss({
        tokens: primitiveForSd,
        destination: "primitive.css",
        selector: ":root",
      })) +
      "\n" +
      emitTypographyCss(primitive.typography) +
      "\n",
  );

  // ——— role.css ———
  const roleLightCss = await buildCss({
    sourceFile: FILES.roleLight,
    includes: [FILES.primitive],
    destination: "_role_light.css",
    selector: '[data-mode="light"]',
  });
  const roleDarkCss = await buildCss({
    sourceFile: FILES.roleDark,
    includes: [FILES.primitive],
    destination: "_role_dark.css",
    selector: '[data-mode="dark"]',
  });
  writeFileSync(
    join(outDir, "role.css"),
    header("role") + roleLightCss + "\n\n" + roleDarkCss + "\n",
  );
  rmSync(join(outDir, "_role_light.css"), { force: true });
  rmSync(join(outDir, "_role_dark.css"), { force: true });

  // ——— structure.css ———
  writeFileSync(
    join(outDir, "structure.css"),
    header("structure") +
      (await buildCss({
        sourceFile: FILES.structure,
        includes: [FILES.primitive],
        destination: "structure.css",
        selector: ":root",
      })) +
      "\n",
  );

  // ——— overlay.css (mode-locked) ———
  writeFileSync(
    join(outDir, "overlay.css"),
    header("overlay") +
      (await buildCss({
        sourceFile: FILES.overlay,
        includes: [FILES.primitive],
        destination: "overlay.css",
        selector: ":root",
      })) +
      "\n",
  );

  // ——— surface.css (mode × context) ———
  const surfaceChunks = [];
  for (const mode of ["light", "dark"]) {
    for (const context of ["canvas", "surface", "surface-raised"]) {
      // Emit every key on the context (level-*, border, field, field-hover, …)
      const slice = { surface: { ...surface[mode][context] } };
      surfaceChunks.push(
        await buildCss({
          tokens: slice,
          includes: [FILES.primitive],
          destination: `_surface_${mode}_${context}.css`,
          // Descendant form for nested context under root mode; compound for same-element.
          selector: `[data-mode="${mode}"] [data-context="${context}"], [data-mode="${mode}"][data-context="${context}"]`,
        }),
      );
    }
  }
  writeFileSync(join(outDir, "surface.css"), header("surface") + surfaceChunks.join("\n\n") + "\n");

  // Flat surface refs so component aliases like {surface.border} resolve to var(--surface-border).
  // Runtime values still come from surface.css selectors (mode × context).
  const surfaceRefsFile = "_surface_refs.json";
  writeFileSync(
    join(tokensDir, surfaceRefsFile),
    JSON.stringify({ surface: { ...surface.light.canvas } }, null, 2),
  );

  // ——— component.css ———
  const { root: componentRoot, light: componentLight, dark: componentDark } =
    splitComponentModes(component);
  const componentParts = [
    await buildCss({
      tokens: componentRoot,
      includes: [FILES.primitive, FILES.structure, FILES.roleLight, surfaceRefsFile],
      destination: "_component_root.css",
      selector: ":root",
    }),
  ];
  if (Object.keys(componentLight).length) {
    componentParts.push(
      await buildCss({
        tokens: componentLight,
        includes: [FILES.primitive, surfaceRefsFile],
        destination: "_component_light.css",
        selector: '[data-mode="light"]',
      }),
    );
  }
  if (Object.keys(componentDark).length) {
    componentParts.push(
      await buildCss({
        tokens: componentDark,
        includes: [FILES.primitive, surfaceRefsFile],
        destination: "_component_dark.css",
        selector: '[data-mode="dark"]',
      }),
    );
  }
  writeFileSync(
    join(outDir, "component.css"),
    header("component") + componentParts.join("\n\n") + "\n",
  );
  rmSync(join(tokensDir, surfaceRefsFile), { force: true });

  // ——— tokens.json (flat catalog for TokenBrowser + runtime editor) ———
  writeFileSync(
    join(outDir, "tokens.json"),
    JSON.stringify(
      buildTokenCatalog({
        primitive,
        roleLight,
        roleDark,
        surface,
        structure,
        overlay,
        component,
      }),
      null,
      2,
    ) +
      "\n",
  );

  // ——— hard gate: references must survive ———
  const roleOut = readFileSync(join(outDir, "role.css"), "utf8");
  const strong = roleOut.match(/--bg-neutral-strong:\s*([^;]+);/);
  if (!strong) {
    console.error("FAIL: --bg-neutral-strong not found in role.css");
    process.exit(1);
  }
  if (strong[1].includes("#") || !strong[1].includes("var(--")) {
    console.error(
      `FAIL: --bg-neutral-strong must be a var() reference, got: ${strong[1].trim()}`,
    );
    process.exit(1);
  }

  console.log("tokens:build OK");
  console.log(`  --bg-neutral-strong: ${strong[1].trim()}`);
  console.log(`  output → ${outDir}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
